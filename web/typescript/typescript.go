// Config says what the TypeScript files describe and where they go.
type Config struct {
	// Dir is the folder the files are written to, relative to the
	// working directory: "frontend/src/types" if empty.
	Dir string
	// Prefix is the path of the API's routes ("/api/v1"): api.ts's
	// client has a function for each typed handler at or below it. ""
	// leaves the client out; the types of every typed handler's input
	// and result are written all the same.
	Prefix string
	// Inertia, when set, adds pages.ts: the props of the pages it lists
	// (inertia.WithPages) and its shared props.
	Inertia *inertia.Inertia
	// Routes adds routes.ts: route(name, params, query), the path of each
	// named route, typed by the names and their parameters, so a
	// renamed route fails the frontend's type check. Since v0.6.
	Routes bool
	// ExcludeRoutes are prefixes of route names routes.ts leaves out
	// ("admin."): routes the frontend doesn't link to, whose paths would
	// otherwise be in its bundle. Since v0.6.
	ExcludeRoutes []string
}

func (cfg Config) dir() string { return cmp.Or(cfg.Dir, filepath.Join("frontend", "src", "types")) }

// header starts every file.
const header = "// Code generated by `go run . types` from the app's Go types. DO NOT EDIT.\n\n"

// Generate returns the TypeScript files of r's typed handlers and cfg's
// pages, by path (Dir joined with "api.ts", "pages.ts" and "routes.ts"), and warnings
// about what it couldn't describe. The same routes, pages and Config
// always give the same bytes.
func Generate(r *web.Router, cfg Config) (map[string][]byte, []string, error) {
	g := &generator{cfg: cfg, set: jsonschema.NewSet(), ids: map[string]bool{}}
	for _, rt := range r.Routes() {
		if rt.Input == nil || rt.Method == "" {
			continue
		}
		g.route(rt)
	}
	if cfg.Inertia != nil {
		g.inertia(cfg.Inertia)
	}
	jsonschema.NameComponents(g.set.Components())
	g.name()
	files := map[string][]byte{filepath.Join(cfg.dir(), "api.ts"): g.apiFile()}
	if cfg.Inertia != nil {
		files[filepath.Join(cfg.dir(), "pages.ts")] = g.pagesFile()
	}
	if cfg.Routes {
		files[filepath.Join(cfg.dir(), "routes.ts")] = routesFile(r, cfg.ExcludeRoutes)
	}
	return files, g.set.Warnings(), nil
}

// Check returns an error unless the files hold what [Generate] writes:
// in a test, it catches a Go type changed without the frontend's types.
// The error says how to fix it.
func Check(r *web.Router, cfg Config) error {
	files, _, err := Generate(r, cfg)
	if err != nil {
		return err
	}
	for _, path := range slices.Sorted(mapsKeys(files)) {
		have, err := os.ReadFile(path)
		if errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("typescript: %s doesn't exist: write it with `go run . types`", path)
		}
		if err != nil {
			return fmt.Errorf("typescript: %w", err)
		}
		if !bytes.Equal(bytes.ReplaceAll(have, []byte("\r\n"), []byte("\n")), files[path]) {
			return fmt.Errorf("typescript: %s is out of date: update it with `go run . types`", path)
		}
	}
	return nil
}

// Register adds the types command to app, which writes the files of
// srv's routes and cfg's pages (only those that changed), or, with
// --check, fails if they are out of date. Call it after adding the
// routes; go tool anetos generate and anetos dev run it. The command
// runs setup without starting the app: it needs the app's settings, not
// its database.
func Register(app *anetos.App, srv *web.Server, cfg Config) error {
	if slices.ContainsFunc(app.Commands(), func(c cmd.Command) bool { return c.Name == "types" }) {
		return errors.New("typescript: Register called twice for one app")
	}
	return app.AddCommand(cmd.Command{
		Name:        "types",
		Usage:       "[--check]",
		Description: "Write the frontend's TypeScript types (" + cfg.dir() + "), or check they're up to date",
		ManagesApp:  true, // the routes and pages are all it needs
		Run: func(ctx context.Context, args *cmd.Args) error {
			return run(ctx, args, srv.Router(), cfg)
		},
	})
}

func run(_ context.Context, args *cmd.Args, r *web.Router, cfg Config) error {
	fs := flag.NewFlagSet("types", flag.ContinueOnError)
	check := fs.Bool("check", false, "fail if the files are out of date, instead of writing them")
	if err := args.Parse(fs); err != nil {
		return err
	}
	if fs.NArg() > 0 {
		return cmd.Usagef("unexpected argument %q", fs.Arg(0))
	}
	if *check {
		if err := Check(r, cfg); err != nil {
			return err
		}
		fmt.Fprintf(args.Stdout, "%s is up to date\n", cfg.dir())
		return nil
	}
	files, warnings, err := Generate(r, cfg)
	if err != nil {
		return err
	}
	for _, w := range warnings {
		fmt.Fprintln(args.Stderr, "warning:", w)
	}
	for _, path := range slices.Sorted(mapsKeys(files)) {
		if have, err := os.ReadFile(path); err == nil && bytes.Equal(have, files[path]) {
			continue // unchanged: Vite doesn't reload for it
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return fmt.Errorf("typescript: %w", err)
		}
		if err := os.WriteFile(path, files[path], 0o644); err != nil { //nolint:gosec // source to commit, readable like the code
			return fmt.Errorf("typescript: %w", err)
		}
		fmt.Fprintf(args.Stdout, "wrote %s\n", path)
	}
	return nil
}

func mapsKeys[V any](m map[string]V) func(func(string) bool) {
	return func(yield func(string) bool) {
		for k := range m {
			if !yield(k) {
				return
			}
		}
	}
}

// ---- What is described ----

type generator struct {
	cfg    Config
	set    *jsonschema.Set
	ids    map[string]bool
	ops    []*operation
	used   map[string]bool // the files' names
	pageTs []*pageType     // the pages' props, then the shared ones
	pages  []page
	shared []*pageType
	errors *pageType
}

// operation is a typed handler the client calls.
type operation struct {
	id, method, path string
	input            string  // its input's type name
	params           []param // path, query and header
	body             []field // the JSON body's fields, or the form's
	form             bool    // a multipart form (the input has files)
	out              *jsonschema.Schema
	empty            bool // no body in the response
}

type param struct {
	in, name string
	schema   *jsonschema.Schema
	required bool
}

type field struct {
	name     string
	schema   *jsonschema.Schema
	required bool
}

// pageType is a props type: a page's, or shared.
type pageType struct {
	typ    reflect.Type
	name   string
	fields []field
	isMap  bool // inertia.Props
}

type page struct {
	component string
	props     *pageType
}

var (
	responderType = reflect.TypeFor[web.Responder]()
	emptyType     = reflect.TypeFor[web.Empty]()
)

// route records rt's types and, under Prefix, its client function.
func (g *generator) route(rt web.RouteInfo) {
	op := &operation{method: rt.Method, path: rt.Pattern}
	in := rt.Input
	ps := params(in)
	// The path's wildcards (a string when the input lacks one), then the
	// query and the headers, as web/openapi describes them.
	for _, m := range wildcard.FindAllStringSubmatch(rt.Pattern, -1) {
		i := slices.IndexFunc(ps, func(p formField) bool { return p.in == "path" && p.name == m[1] })
		if i < 0 {
			op.params = append(op.params, param{"path", m[1], &jsonschema.Schema{Type: "string"}, true})
			continue
		}
		op.params = append(op.params, g.param(ps[i], true))
	}
	for _, p := range ps {
		if p.in == "path" {
			continue // above if the pattern has it; else never set
		}
		if p.in == "header" && p.field.Type.Kind() == reflect.Slice {
			g.set.Warn("%s %s: the header %s is a list, which the client sends as one value, its items joined by commas", rt.Method, rt.Pattern, p.name)
		}
		op.params = append(op.params, g.param(p, jsonfield.Has(p.field.Tag.Get("validate"), "required")))
	}
	if rt.Method != http.MethodGet && rt.Method != http.MethodHead {
		forms := formFields(in)
		if slices.ContainsFunc(forms, func(f formField) bool { return jsonschema.IsFile(f.field.Type) }) {
			op.form = true
			for _, f := range forms {
				tag := f.field.Tag.Get("validate")
				req := jsonfield.Has(tag, "required")
				sc := g.set.Of(f.field.Type, tag, req, true)
				if jsonschema.IsFile(f.field.Type) {
					sc = &jsonschema.Schema{Type: "string", Format: "binary"}
					if f.field.Type.Kind() == reflect.Slice {
						sc = &jsonschema.Schema{Type: "array", Items: sc}
					}
				}
				op.body = append(op.body, field{f.name, sc, req})
			}
		} else {
			if slices.ContainsFunc(jsonfield.Of(in), func(f jsonfield.Field) bool { return !jsonschema.NotInBody(f.Field) }) {
				g.set.Of(in, "", false, true) // the body's type, as a form's (NoteInput)
			}
			for _, f := range jsonfield.Of(in) {
				if jsonschema.NotInBody(f.Field) {
					continue
				}
				sc, req := g.set.Field(f, true)
				op.body = append(op.body, field{f.Name, sc, req})
			}
		}
	}
	switch out := rt.Output; {
	case out.Implements(responderType) || out.Kind() == reflect.Interface:
		op.out = &jsonschema.Schema{Any: true}
	case out == emptyType || rt.Status == http.StatusNoContent || rt.Status == http.StatusResetContent:
		op.empty = true
	default:
		op.out = g.set.Of(out, "", false, false)
	}
	prefix := strings.TrimSuffix(g.cfg.Prefix, "/")
	if g.cfg.Prefix == "" || rt.Pattern != prefix && !strings.HasPrefix(rt.Pattern, prefix+"/") {
		return // its types only
	}
	op.id = g.operationID(rt)
	g.ops = append(g.ops, op)
}

// wildcard is a pattern's wildcard: {id}, or {path...}.
var wildcard = regexp.MustCompile(`\{([^}]*?)(\.\.\.)?\}`)

// param is a path, query or header parameter's description.
func (g *generator) param(p formField, required bool) param {
	sc := g.set.Of(p.field.Type, p.field.Tag.Get("validate"), required, true)
	for _, s := range append([]*jsonschema.Schema{sc}, sc.AnyOf...) {
		s.Nullable = false // a parameter is absent or has a value
	}
	if d := p.field.Tag.Get("description"); d != "" {
		sc.Description = d
	}
	return param{p.in, p.name, sc, required}
}

// inertia records the pages' and shared props' types, and ErrorProps.
func (g *generator) inertia(in *inertia.Inertia) {
	for _, p := range in.Pages() {
		g.pages = append(g.pages, page{p.Component(), g.propsType(p.PropsType())})
	}
	for _, t := range in.SharedTypes() {
		g.shared = append(g.shared, g.propsType(t))
	}
	g.errors = g.propsType(reflect.TypeFor[inertia.ErrorProps]())
}

// propsType is the type of props t (a struct or inertia.Props), each
// type once: a Prop's value may be left out.
func (g *generator) propsType(t reflect.Type) *pageType {
	for _, pt := range g.pageTs {
		if pt.typ == t {
			return pt
		}
	}
	pt := &pageType{typ: t}
	g.pageTs = append(g.pageTs, pt)
	if t.Kind() != reflect.Struct {
		pt.isMap = true
		return pt
	}
	fields, _ := jsonfield.Written(t)
	for _, f := range fields {
		if f.Name == "errors" {
			continue
		}
		if vt, ok := inertia.PropType(f.Field.Type); ok {
			pt.fields = append(pt.fields, field{f.Name, g.set.Of(vt, "", false, false), false})
			continue
		}
		pt.fields = append(pt.fields, field{f.Name, g.set.Of(f.Field.Type, "", false, false), !f.OmitEmpty && !f.ViaPointer})
	}
	return pt
}

// reserved are names the files declare or use, and TypeScript's own.
var reserved = strings.Fields(`Problem ApiOptions ApiError Operation createApi cookie call
	Pages SharedProps PageProps Errors
	Array ArrayBuffer BigInt Blob BodyInit Boolean Date Error File FormData Function Headers JSON
	Map Math Number Object Omit Partial Pick Promise Readonly Record RegExp Request RequestCredentials
	RequestInit Required Response Set String Symbol URL URLSearchParams
	any bigint boolean never null number object string symbol undefined unknown void
	break case catch class const continue debugger default delete do else enum export extends
	false finally for function if import in instanceof new return super switch this throw true
	try typeof var while with as implements interface let package private protected public
	static yield keyof type infer is asserts declare module namespace readonly`)

// name gives the components, the inputs and the props types their
// TypeScript names: identifiers, apart from each other and the files'
// own names ("handlers.Order" is HandlersOrder).
func (g *generator) name() {
	g.used = map[string]bool{}
	for _, n := range reserved {
		g.used[n] = true
	}
	for _, c := range g.set.Components() {
		c.Name = g.unique(typeName(c.Name))
	}
	for _, op := range g.ops {
		op.input = g.unique(ident(pascal(op.id)) + "Input")
	}
	for _, pt := range g.pageTs {
		if !pt.isMap {
			pt.name = g.unique(typeName(jsonschema.BaseName(pt.typ)))
		}
	}
}

// unique returns name, numbered if it is taken, and takes it.
func (g *generator) unique(name string) string {
	n := name
	for i := 2; g.used[n]; i++ {
		n = name + fmt.Sprint(i)
	}
	g.used[n] = true
	return n
}

// operationID names an operation as web/openapi does: the route's name,
// else its handler's method ("Products.Index") or function ("welcome"),
// else its method and path (a closure's, a generic function's).
func (g *generator) operationID(rt web.RouteInfo) string {
	id := rt.Name
	if id == "" {
		if parts := strings.Split(rt.Handler, "."); len(parts) == 3 && !strings.HasPrefix(parts[2], "func") {
			id = parts[1] + "." + parts[2]
		} else if len(parts) == 2 {
			id = parts[1]
		}
	}
	if id == "" {
		id = strings.ToLower(rt.Method) + strings.NewReplacer("/", "_", "{", "", "}", "", ".", "").Replace(rt.Pattern)
	}
	unique := id
	for i := 2; g.ids[unique]; i++ {
		unique = id + fmt.Sprint(i)
	}
	g.ids[unique] = true
	return unique
}

// ---- web.H's binding (as web/openapi reads it) ----

type formField struct {
	in, name string
	field    reflect.StructField
}

// params returns the path, query and header fields of input type t.
func params(t reflect.Type) []formField {
	var out []formField
	for sf := range t.Fields() {
		if sf.Anonymous && sf.Type.Kind() == reflect.Struct && !hasAnyTag(sf, "path", "query", "header", "form", "json") {
			out = append(out, params(sf.Type)...)
			continue
		}
		if !sf.IsExported() {
			continue
		}
		for _, in := range []string{"path", "query", "header"} {
			if name, ok := sf.Tag.Lookup(in); ok && name != "-" && name != "" {
				out = append(out, formField{in, name, sf})
			}
		}
	}
	return out
}

// formFields are the fields web.H binds from a multipart form, by their
// names: a form tag's, else the JSON name of a field without path, query
// or header tags; files included.
func formFields(t reflect.Type) []formField {
	var out []formField
	for sf := range t.Fields() {
		if sf.Anonymous && sf.Type.Kind() == reflect.Struct && !hasAnyTag(sf, "path", "query", "header", "form", "json") {
			out = append(out, formFields(sf.Type)...)
			continue
		}
		if !sf.IsExported() {
			continue
		}
		if name, ok := sf.Tag.Lookup("form"); ok {
			if name != "" && name != "-" {
				out = append(out, formField{"form", name, sf})
			}
			continue
		}
		if hasAnyTag(sf, "path", "query", "header") {
			continue
		}
		tag, ok := sf.Tag.Lookup("json")
		name, _, _ := strings.Cut(tag, ",")
		if !ok || name == "-" || !formBindable(sf.Type) {
			continue // a struct or a map: JSON only
		}
		out = append(out, formField{"form", cmp.Or(name, sf.Name), sf})
	}
	return out
}

// formBindable reports whether web.H fills a field of type t from a form
// value: a file, or a value of a type convert.For converts, or a slice
// of them.
func formBindable(t reflect.Type) bool {
	if jsonschema.IsFile(t) {
		return true
	}
	if t.Kind() == reflect.Slice && t.Elem().Kind() != reflect.Uint8 {
		t = t.Elem()
	}
	_, err := convert.For(t)
	return err == nil
}

func hasAnyTag(sf reflect.StructField, keys ...string) bool {
	for _, k := range keys {
		if _, ok := sf.Tag.Lookup(k); ok {
			return true
		}
	}
	return false
}
