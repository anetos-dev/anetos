func TestPluginsFile(t *testing.T) {
	root := t.TempDir()
	if _, err := ReadPlugins(root); err == nil || !strings.Contains(err.Error(), "plugins.go is missing") {
		t.Errorf("ReadPlugins without the file: %v", err)
	}
	// What anetos new writes is what WritePlugins writes for no plugins.
	if err := WritePlugins(root, nil); err != nil {
		t.Fatal(err)
	}
	tmpl, err := templates.ReadFile("templates/new/plugins.go.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	if got := read(t, filepath.Join(root, PluginsFile)); got != string(tmpl) {
		t.Errorf("templates/new/plugins.go.tmpl differs from WritePlugins(nil):\n%s", got)
	}
	if got, err := ReadPlugins(root); err != nil || len(got) != 0 {
		t.Errorf("ReadPlugins = %v, %v", got, err)
	}

	// Names main declares elsewhere aren't used as import names.
	if err := os.WriteFile(filepath.Join(root, "main.go"), []byte("package main\n\nfunc setup() {}\n\nvar (\n\tstripe, x int\n)\n\ntype T struct{}\n\nfunc (T) postmark() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, "other_test.go"), []byte("package main_test\n\nfunc lives() {}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	paths := []string{
		"anetos.dev/anetos/plugins/postmark",
		"example.com/acme/postmark", // same name
		"example.com/stripe/v2",     // major version suffix
		"example.com/go-type",       // keyword after cleaning
		"example.com/ext",           // the ext import's name
		"example.com/9lives",        // a leading digit
		"example.com/setup",         // declared in main.go
		"example.com/init",          // init
	}
	if err := WritePlugins(root, paths); err != nil {
		t.Fatal(err)
	}
	src := read(t, filepath.Join(root, PluginsFile))
	for _, want := range []string{
		"// Code generated by anetos add. DO NOT EDIT.",
		`postmark "anetos.dev/anetos/plugins/postmark"`,
		`postmark2 "example.com/acme/postmark"`,
		`stripe2 "example.com/stripe/v2"`,
		`setup2 "example.com/setup"`,
		`init2 "example.com/init"`,
		`gotype "example.com/go-type"`,
		`pluginext "example.com/ext"`,
		`lives "example.com/9lives"`,
		"postmark.Plugin(),\n\t\tpostmark2.Plugin(),\n\t\tstripe2.Plugin(),",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("plugins.go lacks %q:\n%s", want, src)
		}
	}
	if got, err := ReadPlugins(root); err != nil || !slices.Equal(got, paths) {
		t.Errorf("ReadPlugins = %v, %v", got, err)
	}
	if err := os.WriteFile(filepath.Join(root, PluginsFile), []byte("package main\nimport (\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := ReadPlugins(root); err == nil {
		t.Error("ReadPlugins of a broken file: no error")
	}
}

func TestImportAlias(t *testing.T) {
	for p, want := range map[string]string{
		"example.com/postmark":   "postmark",
		"example.com/Post_Mark":  "postmark",
		"example.com/x/v10":      "x",
		"example.com/v2":         "examplecom",
		"example.com/plugins":    "pluginplugins",
		"example.com/main":       "pluginmain",
		"example.com/app":        "pluginapp",
		"example.com/func":       "pluginfunc",
		"example.com/---":        "plugin",
		"example.com/anetos-pdf": "anetospdf",
	} {
		if got := importAlias(p); got != want {
			t.Errorf("importAlias(%s) = %s, want %s", p, got, want)
		}
	}
}
