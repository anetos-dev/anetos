// PluginsFile is the file that lists a project's plugins.
const PluginsFile = "plugins.go"

const extPath = "anetos.dev/anetos/ext"

// ReadPlugins returns the import paths of the plugins root/plugins.go
// lists, in the order of its plugins() list.
func ReadPlugins(root string) ([]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, PluginsFile), nil, 0)
	if errors.Is(err, os.ErrNotExist) {
		return nil, fmt.Errorf("%s is missing: it lists the app's plugins, and setup loads them with ext.Load(app, plugins()). Projects made with anetos new have it", PluginsFile)
	}
	if err != nil {
		return nil, err
	}
	byName := map[string]string{}
	var all []string
	for _, imp := range f.Imports {
		p, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return nil, err
		}
		if p == extPath {
			continue
		}
		name := path.Base(p)
		if imp.Name != nil {
			name = imp.Name.Name
		}
		byName[name] = p
		all = append(all, p)
	}
	// The order of the list: pkg.Plugin() calls.
	var paths []string
	ast.Inspect(f, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		if sel, ok := call.Fun.(*ast.SelectorExpr); ok && sel.Sel.Name == "Plugin" {
			if id, ok := sel.X.(*ast.Ident); ok {
				if p, ok := byName[id.Name]; ok && !slices.Contains(paths, p) {
					paths = append(paths, p)
				}
			}
		}
		return true
	})
	for _, p := range all { // imported but not listed
		if !slices.Contains(paths, p) {
			paths = append(paths, p)
		}
	}
	return paths, nil
}

// WritePlugins writes root/plugins.go, listing the plugins of the
// import paths in order: each package's Plugin().
func WritePlugins(root string, paths []string) error {
	var b bytes.Buffer
	b.WriteString(`// Code generated by anetos add. DO NOT EDIT.

package main

import (
	"anetos.dev/anetos/ext"
`)
	// An import's name can't be one the package declares.
	used, err := packageNames(root)
	if err != nil {
		return err
	}
	used["ext"] = true
	aliases := make([]string, len(paths))
	if len(paths) > 0 {
		b.WriteString("\n")
	}
	for i, p := range paths {
		alias := importAlias(p)
		for n := 2; used[alias]; n++ {
			alias = importAlias(p) + strconv.Itoa(n)
		}
		used[alias] = true
		aliases[i] = alias
		fmt.Fprintf(&b, "\t%s %q\n", alias, p)
	}
	b.WriteString(`)

// plugins returns the app's plugins, in the order they were added:
// anetos add and anetos remove rewrite this file. setup loads them with
// ext.Load.
func plugins() []ext.Plugin {
	return []ext.Plugin{
`)
	for _, a := range aliases {
		fmt.Fprintf(&b, "\t\t%s.Plugin(),\n", a)
	}
	b.WriteString("\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, PluginsFile), src, 0o644)
}

// packageNames returns the names package main declares in root's other
// files (tests included), and init.
func packageNames(root string) (map[string]bool, error) {
	names := map[string]bool{"init": true}
	files, err := filepath.Glob(filepath.Join(root, "*.go"))
	if err != nil {
		return nil, err
	}
	for _, file := range files {
		if filepath.Base(file) == PluginsFile {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), file, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		if f.Name.Name != "main" {
			continue
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					names[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					switch spec := spec.(type) {
					case *ast.TypeSpec:
						names[spec.Name.Name] = true
					case *ast.ValueSpec:
						for _, n := range spec.Names {
							names[n.Name] = true
						}
					}
				}
			}
		}
	}
	return names, nil
}

// importAlias returns a Go identifier for the package at p: its last
// element without a major version suffix ("/v2"), letters and digits
// only.
func importAlias(p string) string {
	base := path.Base(p)
	if len(base) > 1 && base[0] == 'v' && strings.Trim(base[1:], "0123456789") == "" {
		base = path.Base(path.Dir(p))
	}
	var b strings.Builder
	for _, r := range base {
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			b.WriteRune(unicode.ToLower(r))
		}
	}
	alias := strings.TrimLeftFunc(b.String(), unicode.IsDigit)
	if alias == "" || token.IsKeyword(alias) || slices.Contains([]string{"main", "plugins", "app", "ext"}, alias) {
		alias = "plugin" + alias
	}
	return alias
}
