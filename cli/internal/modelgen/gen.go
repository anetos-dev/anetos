// Package modelgen implements `anetos gen`: it finds the models in Go
// packages and writes a models_gen.go file declaring their typed columns.
//
// A model is a struct type that embeds db.Model, db.Timestamps or
// db.SoftDeletes (directly or through other embedded structs), has a
// TableName method, or has a //anetos:model directive in its doc comment.
// A //anetos:skip directive excludes a struct.
package modelgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/build/constraint"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

// FileName is the name of the file written in each package with models.
const FileName = "models_gen.go"

// Header is the first line of every generated file. A models_gen.go
// without it is never overwritten or removed.
const Header = "// Code generated by anetos gen. DO NOT EDIT."

// Change is a file to write, or to remove when Content is nil.
type Change struct {
	Path    string // absolute
	Content []byte
	Models  []string
}

// Generate loads the packages matching patterns (relative to dir) and
// returns the generated files that differ from what is on disk.
func Generate(dir string, patterns ...string) ([]Change, error) {
	if len(patterns) == 0 {
		patterns = []string{"./..."}
	}
	roots, overlay, err := candidates(dir, patterns)
	if err != nil || len(roots) == 0 {
		return nil, err
	}
	cfg := &packages.Config{
		Mode:    packages.NeedName | packages.NeedFiles | packages.NeedSyntax | packages.NeedTypes,
		Dir:     dir,
		Overlay: overlay,
	}
	pkgs, err := packages.Load(cfg, roots...)
	if err != nil {
		return nil, fmt.Errorf("anetos gen: %w", err)
	}
	var changes []Change
	var errs []error
	for _, pkg := range pkgs {
		c, err := generatePackage(pkg)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		if c != nil {
			changes = append(changes, *c)
		}
	}
	sort.Slice(changes, func(i, j int) bool { return changes[i].Path < changes[j].Path })
	return changes, errors.Join(errs...)
}

// Apply writes (or removes) the changed files.
func Apply(changes []Change) error {
	for _, c := range changes {
		if c.Content == nil {
			if err := os.Remove(c.Path); err != nil && !errors.Is(err, os.ErrNotExist) {
				return err
			}
			continue
		}
		tmp, err := os.CreateTemp(filepath.Dir(c.Path), ".models_gen-*.go.tmp")
		if err != nil {
			return err
		}
		_, werr := tmp.Write(c.Content)
		if err := errors.Join(werr, tmp.Chmod(0o644), tmp.Close()); err != nil {
			_ = os.Remove(tmp.Name())
			return err
		}
		if err := os.Rename(tmp.Name(), c.Path); err != nil {
			_ = os.Remove(tmp.Name())
			return err
		}
	}
	return nil
}

// candidates lists the packages worth type-checking: those that import
// the db package (directly or not), mention TableName or a anetos
// directive, or have a generated file. Generated files are replaced by an
// empty file in the overlay, so stale ones can't break type checking.
func candidates(dir string, patterns []string) (roots []string, overlay map[string][]byte, err error) {
	cfg := &packages.Config{Mode: packages.NeedName | packages.NeedFiles | packages.NeedImports | packages.NeedDeps, Dir: dir}
	pkgs, err := packages.Load(cfg, patterns...)
	if err != nil {
		return nil, nil, fmt.Errorf("anetos gen: %w", err)
	}
	usesDB := map[*packages.Package]bool{}
	var uses func(p *packages.Package) bool
	uses = func(p *packages.Package) bool {
		if v, ok := usesDB[p]; ok {
			return v
		}
		usesDB[p] = false // cycles can't happen, but be safe
		v := p.PkgPath == dbPath
		for _, imp := range p.Imports {
			v = v || uses(imp)
		}
		usesDB[p] = v
		return v
	}
	overlay = map[string][]byte{}
	var errs []error
	for _, pkg := range pkgs {
		for _, e := range pkg.Errors {
			if e.Kind == packages.ListError && len(pkg.GoFiles) == 0 {
				errs = append(errs, fmt.Errorf("anetos gen: %s", e.Msg))
			}
		}
		if len(pkg.GoFiles) == 0 {
			continue
		}
		gen := filepath.Join(filepath.Dir(pkg.GoFiles[0]), FileName)
		want := uses(pkg)
		for _, f := range pkg.GoFiles {
			src, err := os.ReadFile(f)
			if err != nil {
				return nil, nil, err
			}
			if f == gen {
				if !ours(src) {
					errs = append(errs, fmt.Errorf("anetos gen: %s was not written by anetos gen; rename it", f))
					continue
				}
				overlay[f] = []byte("package " + pkg.Name + "\n")
				want = true
				continue
			}
			if bytes.Contains(src, []byte("TableName")) || bytes.Contains(src, []byte("//anetos:")) {
				want = true
			}
		}
		if want {
			roots = append(roots, pkg.PkgPath)
		}
	}
	return roots, overlay, errors.Join(errs...)
}

type model struct {
	name string
	cols []column
}

func generatePackage(pkg *packages.Package) (*Change, error) {
	// Syntax errors stop generation. Other errors (such as code using a
	// column that isn't generated yet) matter only if a model's field
	// types are broken; findModels checks.
	var parseErrs []error
	for _, e := range pkg.Errors {
		if e.Kind == packages.ParseError {
			parseErrs = append(parseErrs, errors.New(e.Error()))
		}
	}
	if len(parseErrs) > 0 || pkg.Types == nil || len(pkg.GoFiles) == 0 {
		return nil, errors.Join(parseErrs...)
	}
	gen := filepath.Join(filepath.Dir(pkg.GoFiles[0]), FileName)
	models, err := findModels(pkg, gen)
	if err != nil {
		return nil, err
	}
	old, err := os.ReadFile(gen)
	exists := err == nil
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}
	if exists && !ours(old) {
		// Possibly excluded from the build by a build constraint.
		return nil, fmt.Errorf("anetos gen: %s was not written by anetos gen; rename it", gen)
	}
	if len(models) == 0 {
		if exists {
			return &Change{Path: gen}, nil // remove the stale file
		}
		return nil, nil
	}
	src, err := render(pkg, models)
	if err != nil {
		return nil, err
	}
	if exists && bytes.Equal(bytes.ReplaceAll(old, []byte("\r\n"), []byte("\n")), src) {
		return nil, nil
	}
	names := make([]string, len(models))
	for i, m := range models {
		names[i] = m.name
	}
	return &Change{Path: gen, Content: src, Models: names}, nil
}

// findModels returns the package's models in source order.
func findModels(pkg *packages.Package, gen string) ([]model, error) {
	type found struct {
		pos token.Position
		m   model
	}
	var all []found
	var errs []error
	typeErrs := false
	byName := map[string]*ast.File{}
	for _, file := range pkg.Syntax {
		byName[pkg.Fset.File(file.Pos()).Name()] = file
	}
	isConstrained := func(pos token.Pos) bool {
		tf := pkg.Fset.File(pos)
		if tf == nil {
			return false
		}
		f, ok := byName[tf.Name()]
		return ok && constrained(tf.Name(), f)
	}
	for _, file := range pkg.Syntax {
		if pkg.Fset.File(file.Pos()).Name() == gen {
			continue
		}
		for _, decl := range file.Decls {
			gd, ok := decl.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, spec := range gd.Specs {
				ts := spec.(*ast.TypeSpec)
				docs := []*ast.CommentGroup{ts.Doc}
				if len(gd.Specs) == 1 {
					docs = append(docs, gd.Doc)
				}
				marked, skip, err := directives(pkg.Fset, ts.Name.Name, docs)
				if err != nil {
					errs = append(errs, err)
					continue
				}
				if skip || ts.Name.Name == "_" {
					continue
				}
				pos := pkg.Fset.Position(ts.Pos())
				if ts.TypeParams != nil || ts.Assign.IsValid() {
					if marked {
						errs = append(errs, fmt.Errorf("%s: %s: generic types and aliases can't be models", pos, ts.Name.Name))
					}
					continue
				}
				obj, ok := pkg.Types.Scope().Lookup(ts.Name.Name).(*types.TypeName)
				if !ok {
					continue // declared inside a function scope? not at package level
				}
				st, isStruct := obj.Type().Underlying().(*types.Struct)
				if !isStruct || isValueType(obj.Type()) {
					if marked {
						errs = append(errs, fmt.Errorf("%s: %s is marked //anetos:model but is not a model struct", pos, ts.Name.Name))
					}
					continue
				}
				if !marked && !isModelType(obj.Type(), st) {
					continue
				}
				if constrained(pkg.Fset.File(ts.Pos()).Name(), file) {
					errs = append(errs, fmt.Errorf("%s: %s: models in files with build constraints aren't supported (the generated file would depend on the platform); move it to a file without them, or mark it //anetos:skip", pos, ts.Name.Name))
					continue
				}
				if hasInvalid(st) {
					typeErrs = true
					continue
				}
				w := &walker{fset: pkg.Fset, model: obj, self: pkg.Types, constrained: isConstrained}
				cols, err := w.columns(st)
				if err != nil {
					errs = append(errs, err)
					continue
				}
				if colsInvalid(cols) {
					typeErrs = true
					continue
				}
				all = append(all, found{pos, model{ts.Name.Name, cols}})
			}
		}
	}
	if typeErrs {
		for _, e := range pkg.Errors {
			errs = append(errs, errors.New(e.Error()))
		}
		errs = append(errs, fmt.Errorf("anetos gen: %s: fix the errors above; a model's field types must compile", pkg.PkgPath))
	}
	sort.SliceStable(all, func(i, j int) bool {
		if all[i].pos.Filename != all[j].pos.Filename {
			return all[i].pos.Filename < all[j].pos.Filename
		}
		return all[i].pos.Offset < all[j].pos.Offset
	})
	models := make([]model, len(all))
	for i, f := range all {
		models[i] = f.m
	}
	return models, errors.Join(errs...)
}

// directives reads //anetos:model and //anetos:skip from doc comments.
func directives(fset *token.FileSet, name string, docs []*ast.CommentGroup) (model, skip bool, err error) {
	for _, g := range docs {
		if g == nil {
			continue
		}
		for _, c := range g.List {
			d, ok := strings.CutPrefix(c.Text, "//anetos:")
			if !ok {
				continue
			}
			switch strings.TrimSpace(d) {
			case "model":
				model = true
			case "skip":
				skip = true
			default:
				return false, false, fmt.Errorf("%s: %s: unknown directive %s (known: //anetos:model, //anetos:skip)", fset.Position(c.Pos()), name, c.Text)
			}
		}
	}
	return model, skip, nil
}

// hasInvalid reports whether a field's type failed to type-check.
func hasInvalid(st *types.Struct) bool {
	for f := range st.Fields() {
		if strings.Contains(types.TypeString(f.Type(), nil), "invalid type") {
			return true
		}
	}
	return false
}

// varName is the name of the generated variable: PostCols, or postCols
// for an unexported model.
func varName(model string) string { return model + "Cols" }

// colsInvalid reports whether a column's type (possibly from an embedded
// struct) failed to type-check.
func colsInvalid(cols []column) bool {
	for _, c := range cols {
		if strings.Contains(types.TypeString(c.typ, nil), "invalid type") {
			return true
		}
	}
	return false
}

// ours reports whether src starts with the generated-file header (with
// Unix or Windows line endings).
func ours(src []byte) bool {
	return bytes.HasPrefix(src, []byte(Header+"\n")) || bytes.HasPrefix(src, []byte(Header+"\r\n"))
}

// constrained reports whether a file is built only on some platforms or
// with some tags: a //go:build line, or a _GOOS / _GOARCH file name.
func constrained(path string, f *ast.File) bool {
	for _, g := range f.Comments {
		if g.Pos() > f.Package {
			break
		}
		for _, c := range g.List {
			if constraint.IsGoBuild(c.Text) || constraint.IsPlusBuild(c.Text) {
				return true
			}
		}
	}
	name := strings.TrimSuffix(filepath.Base(path), ".go")
	parts := strings.Split(name, "_")
	if len(parts) < 2 {
		return false
	}
	last := parts[len(parts)-1]
	if knownOS[last] || knownArch[last] {
		return true
	}
	return false
}

var knownOS = setOf("aix android darwin dragonfly freebsd hurd illumos ios js linux nacl netbsd openbsd plan9 solaris wasip1 windows zos")

var knownArch = setOf("386 amd64 amd64p32 arm armbe arm64 arm64be loong64 mips mipsle mips64 mips64le mips64p32 mips64p32le ppc ppc64 ppc64le riscv riscv64 s390 s390x sparc sparc64 wasm")

func setOf(words string) map[string]bool {
	m := map[string]bool{}
	for w := range strings.FieldsSeq(words) {
		m[w] = true
	}
	return m
}
