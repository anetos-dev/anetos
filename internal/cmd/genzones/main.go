// Command genzones writes i18n/zones.go, the time zones users choose
// from (i18n.TimeZones), from the IANA database's zone.tab: one zone per
// region of each country, sorted, with UTC first.
//
//	go run ./internal/cmd/genzones /usr/share/zoneinfo/zone.tab > i18n/zones.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"slices"
	"strings"
	"time"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: genzones <zone.tab>")
		os.Exit(2)
	}
	b, err := os.ReadFile(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var zones []string
	version := ""
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "#") || line == "" {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 3 {
			continue
		}
		if _, err := time.LoadLocation(fields[2]); err != nil {
			fmt.Fprintf(os.Stderr, "genzones: %s doesn't load: %v\n", fields[2], err)
			os.Exit(1)
		}
		zones = append(zones, fields[2])
	}
	if err := sc.Err(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if zi, err := os.ReadFile(strings.TrimSuffix(os.Args[1], "zone.tab") + "tzdata.zi"); err == nil {
		first, _, _ := strings.Cut(string(zi), "\n")
		version = strings.TrimPrefix(first, "# version ")
	}
	slices.Sort(zones)
	zones = slices.Compact(zones)
	var out strings.Builder
	out.WriteString("// Code generated by internal/cmd/genzones from the IANA time zone database")
	if version != "" {
		out.WriteString(" " + version)
	}
	out.WriteString("; DO NOT EDIT.\n\npackage i18n\n\n// zones are the time zones of TimeZones.\nvar zones = []string{\n\t\"UTC\",\n")
	for _, z := range zones {
		fmt.Fprintf(&out, "\t%q,\n", z)
	}
	out.WriteString("}\n")
	os.Stdout.WriteString(out.String())
}
